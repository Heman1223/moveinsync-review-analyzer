"""Write docs/analysis_snapshot.md: the numbers behind the memo (no API calls).

    python -m scripts.report            # last 365 days
    python -m scripts.report --days 90
"""

import argparse

import pandas as pd

from src import analysis, config
from src.collector import load_reviews

OUT = config.ROOT / "docs" / "analysis_snapshot.md"


def md(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False, disable_numparse=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--days", type=int, default=365)
    args = parser.parse_args()

    data = analysis.prepare(load_reviews())
    snaps = pd.read_csv(config.SNAPSHOTS_CSV) if config.SNAPSHOTS_CSV.exists() else None
    lines = [f"# Analysis snapshot (last {args.days} days)", "",
             "Generated by `python -m scripts.report`. Written reviews only; store figures from the latest snapshot.", ""]

    for app_id, meta in config.APPS.items():
        app = analysis.filter_period(data, app_id)
        df = analysis.filter_period(app, start=analysis.period_start(app, args.days))
        k = analysis.kpis(df, analysis.latest_snapshot(snaps, app_id))
        rh, cov = analysis.reply_health(df), analysis.uncategorised(df)
        summary = analysis.issue_summary(df)
        lines += [f"## {meta['name']} (`{app_id}`)", "",
                  f"- Period: {k['date_from']:%d %b %Y} to {k['date_to']:%d %b %Y}; {k['reviews']:,} written reviews, "
                  f"{k['complaints']:,} complaints (1-3★)",
                  f"- Written-review average **{k['avg_rating']}** ({k['pct_1_star']}% 1★) vs store **{k['store_score']}** "
                  f"({k['store_pct_1_star']}% 1★ across {k['store_ratings']:,} ratings)",
                  f"- Replies to 1-2★ reviews: **{rh['reply_rate_unhappy']}%** ({rh['unhappy_replied']} of {rh['unhappy_reviews']})",
                  f"- Complaints classified: {cov['by_rules']} by rules, {cov['by_llm']} by LLM; "
                  f"{cov['pct_unclassified']}% of substantive complaints unclassified; {cov['low_info']} low-info", ""]
        if summary.empty:
            lines += ["(not enough data)", ""]
            continue
        show = summary[["issue", "fixable_by", "reviews", "pct_of_complaints", "avg_rating", "uplift",
                        "share_before", "share_last_period", "thumbs_up", "safety_flags"]]
        lines += ["### Issues ranked by rating impact (safety pinned)", "", md(show), ""]
        lines += ["### Fix these first", ""]
        for i, r in analysis.top_fixes(summary).iterrows():
            lines.append(f"{i + 1}. **{r['issue']}** ({r['fixable_by']}): {r['reviews']} complaints, "
                         f"{r['pct_of_complaints']}% of complaints, could lift written-review average by ~+{r['uplift']:.2f}")
            for ex in analysis.examples(df, r["category"], n=2).itertuples():
                lines.append(f"   - {ex.rating}★ ({ex.review_date:%b %Y}): \"{str(ex.review_text)[:180]}\"")
        lines.append("")
        if app_id == "com.moveinsync.ets":
            vt = analysis.version_table(df)
            lines += ["### By app version", "", md(vt.assign(first_review=vt["first_review"].dt.strftime("%Y-%m-%d"))), ""]
            safety = analysis.safety_reviews(df)
            lines += [f"### Safety-flagged complaints: {len(safety)} (for human review)", ""]
            for s in safety.head(8).itertuples():
                lines.append(f"- {s.rating}★ ({s.review_date:%d %b %Y}): \"{str(s.review_text)[:160]}\"")
            lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(config.ROOT)}")


if __name__ == "__main__":
    main()
